function makeSimpleNotes(pitches: number[], tempo: number): MidiNote[] {
  const secPerBeat = 60 / tempo;
  return pitches.map((p, idx) => ({
    id: `seed_n_${idx}`,
    pitch: p,
    pitchName: midiPitchToName(p),
    startTime: idx * secPerBeat * 0.75,
    duration: secPerBeat * 0.7,
    velocity: 82 + (idx % 3) * 4,
    channel: 0,
  }));
}

